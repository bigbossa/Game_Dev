// Writes the grade-odds table of README.md from the code (C.gradeBands / C.BOSS_GRADES), between the markers
//   <!-- drop-rates:start --> ... <!-- drop-rates:end -->
// Run after changing any drop %:  npm run drop-table        (--check: fail when the README is out of date)
const fs = require('node:fs'), path = require('node:path');
const C = require('../shared/world-data');
const file = path.join(__dirname, '..', 'README.md');
const START = '<!-- drop-rates:start -->', END = '<!-- drop-rates:end -->';
const pct = (v) => `${+(v * 100).toPrecision(v >= 0.01 ? 3 : 2)}%`;
const hi = C.GRADES.slice(3);
const rows = C.gradeBands().map((b) =>
  `| Lv.${b.from}${b.to ? `–${b.to}` : ' ขึ้นไป'} | ×${b.mul} | ${b.chances.slice(3).map(pct).join(' | ')} |`);
const boss = C.gradeChances(1, 1, true).slice(3).map(pct).join(' | ');
const table = [
  START,
  '<!-- generated by tools/drop-table.cjs (npm run drop-table): edit HIGH_BANDS / BOSS_GRADES / GRADES in shared/common.js, not this table -->',
  `| มอนสเตอร์ | ตัวคูณ | ${hi.map((g) => g.name).join(' | ')} |`,
  `|---|---:|${hi.map(() => '---:').join('|')}|`,
  ...rows,
  `| บอสทุกแผนที่ (ได้ 1 ชิ้นแน่นอน) | – | ${boss} |`,
  END,
].join('\n');

const readme = fs.readFileSync(file, 'utf8');
const a = readme.indexOf(START), b = readme.indexOf(END);
if (a < 0 || b < a) { console.error(`README.md has no ${START} … ${END} block`); process.exit(1); }
const next = readme.slice(0, a) + table + readme.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== readme) { console.error('README drop-rate table is out of date: run  npm run drop-table'); process.exit(1); }
  console.log('PASS: README drop-rate table matches the code');
} else {
  fs.writeFileSync(file, next);
  console.log(next === readme ? 'README drop-rate table already up to date' : 'README drop-rate table updated');
}
